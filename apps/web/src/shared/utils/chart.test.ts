import { describe, test, expect } from "vitest";
import { calculateAxisMax } from "./chart";

/**
 * グラフスケール（Y軸上限値）計算ユーティリティの単体テスト
 */
describe("calculateAxisMax", () => {
  /**
   * @test データ内の最大値が初期上限以下の場合、スケールを拡張せず初期上限値をそのまま返すことを確認
   */
  test("最大値が初期上限以下の場合は初期上限値を返す", () => {
    // 30万円（データ最大値） <= 50万円（初期上限）の場合は 50万円
    expect(calculateAxisMax(300000, 500000, 500000)).toBe(500000);
  });

  /**
   * @test データ内の最大値が初期上限を超えた場合、指定ステップ幅（50万円刻み）で正しくスケール拡張されることを確認
   */
  test("最大値が初期上限を超えた場合、ステップ幅(50万)刻みで拡張される", () => {
    // 60万円（データ最大値） > 50万円（初期上限）の場合は 100万円 に拡張
    expect(calculateAxisMax(600000, 500000, 500000)).toBe(1000000);
  });

  /**
   * @test 件数モード（初期上限50件、ステップ幅50件）でも同様に正しくスケール拡張されることを確認
   */
  test("件数モード（初期上限50、ステップ幅50）で拡張される", () => {
    // 55件（データ最大値） > 50件（初期上限）の場合は 100件 に拡張
    expect(calculateAxisMax(55, 50, 50)).toBe(100);
  });
});
